CREATE TABLE import_batch (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code varchar(40) NOT NULL UNIQUE,
  asset_id bigint NOT NULL,
  scan_id bigint NOT NULL,
  file_sha256 varchar(64) NOT NULL,
  zap_version text,
  template_name text,
  session_name text,
  report_started_at timestamptz,
  report_ended_at timestamptz,
  imported_by bigint NOT NULL,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  finished_at timestamptz,
  status import_status NOT NULL DEFAULT 'Received',
  total_records integer NOT NULL DEFAULT 0 CHECK (total_records >= 0),
  success_records integer NOT NULL DEFAULT 0 CHECK (success_records >= 0),
  error_records integer NOT NULL DEFAULT 0 CHECK (error_records >= 0),
  failure_code text,
  raw_object_key text NOT NULL UNIQUE,
  raw_original_name text NOT NULL,
  raw_size_bytes bigint NOT NULL CHECK (raw_size_bytes >= 0),
  raw_format text NOT NULL CHECK (raw_format IN ('JSON','XML','Other')),
  raw_key_ref text NOT NULL,
  UNIQUE (asset_id, scan_id, file_sha256),
  UNIQUE (id, scan_id, asset_id),
  CHECK (success_records + error_records <= total_records),
  CHECK (status <> 'Completed' OR (error_records = 0 AND success_records = total_records)),
