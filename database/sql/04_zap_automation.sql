ALTER TABLE zap_artifact
  ADD CONSTRAINT fk_zap_artifact_execution
    FOREIGN KEY (execution_id) REFERENCES zap_execution(id) ON DELETE RESTRICT ON UPDATE RESTRICT;

CREATE INDEX ix_scan_schedule_automation_due
  ON scan_schedule(next_due_at)
  WHERE status = 'Active' AND automation_enabled;
CREATE INDEX ix_zap_execution_queue
  ON zap_execution(requested_at, id)
  WHERE status = 'Queued';
CREATE INDEX ix_zap_execution_expired_lease
  ON zap_execution(lease_expires_at)
  WHERE lease_expires_at IS NOT NULL;
CREATE INDEX ix_zap_artifact_execution ON zap_artifact(execution_id);

CREATE OR REPLACE FUNCTION protect_zap_scan_profile()
RETURNS trigger LANGUAGE plpgsql SET search_path = htqlhdk, pg_temp AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    IF OLD.status <> 'Draft' THEN
      RAISE EXCEPTION 'Approved ZAP profiles must be retained' USING ERRCODE = '23514';
    END IF;
    RETURN OLD;
  END IF;

  IF OLD.status = 'Retired' THEN
    RAISE EXCEPTION 'Retired ZAP profiles are immutable' USING ERRCODE = '23514';
  END IF;

  IF OLD.status = 'Active' THEN
    IF NEW.status NOT IN ('Active', 'Retired') THEN
      RAISE EXCEPTION 'Active ZAP profiles can only be retired' USING ERRCODE = '23514';
    END IF;
    IF NEW.status = 'Retired' AND EXISTS (
      SELECT 1 FROM scan_schedule
      WHERE zap_profile_id = OLD.id AND automation_enabled AND status = 'Active'
    ) THEN
      RAISE EXCEPTION 'Disable active automated schedules before retiring their ZAP profile'
        USING ERRCODE = '23514';
    END IF;
    IF ROW(NEW.code, NEW.name, NEW.version_no, NEW.spider_kind,
           NEW.active_scan_enabled, NEW.auth_kind, NEW.auth_header_name,
           NEW.auth_secret_ref, NEW.spider_max_minutes, NEW.passive_wait_max_minutes,
           NEW.active_scan_max_minutes, NEW.max_rule_minutes, NEW.request_delay_ms,
           NEW.thread_per_host, NEW.service_user_id, NEW.created_by, NEW.created_at,
           NEW.approved_by, NEW.approved_at)
       IS DISTINCT FROM
       ROW(OLD.code, OLD.name, OLD.version_no, OLD.spider_kind,
           OLD.active_scan_enabled, OLD.auth_kind, OLD.auth_header_name,
           OLD.auth_secret_ref, OLD.spider_max_minutes, OLD.passive_wait_max_minutes,
           OLD.active_scan_max_minutes, OLD.max_rule_minutes, OLD.request_delay_ms,
           OLD.thread_per_host, OLD.service_user_id, OLD.created_by, OLD.created_at,
           OLD.approved_by, OLD.approved_at) THEN
      RAISE EXCEPTION 'Active ZAP profile configuration is immutable; create a new version'
        USING ERRCODE = '23514';
    END IF;
  END IF;
  RETURN NEW;
END $$;

CREATE TRIGGER protect_zap_scan_profile_version
BEFORE UPDATE OR DELETE ON zap_scan_profile
FOR EACH ROW EXECUTE FUNCTION protect_zap_scan_profile();

CREATE OR REPLACE FUNCTION guard_automated_schedule()
RETURNS trigger LANGUAGE plpgsql SET search_path = htqlhdk, pg_temp AS $$
DECLARE
  profile_status zap_profile_status;
  recurrence_part text;
  recurrence_key text;
  recurrence_value text;
  seen_keys text[] := ARRAY[]::text[];
BEGIN
  IF NEW.automation_enabled THEN
    IF NEW.frequency = 'Custom' THEN
      RAISE EXCEPTION 'Automated schedule recurrence is unsupported' USING ERRCODE = '23514';
    END IF;

    FOREACH recurrence_part IN ARRAY string_to_array(upper(NEW.recurrence_rule), ';') LOOP
      IF recurrence_part !~ '^[A-Z]+=[A-Z0-9,+-]+$' THEN
        RAISE EXCEPTION 'Automated schedule recurrence is malformed' USING ERRCODE = '23514';
      END IF;
      recurrence_key := split_part(recurrence_part, '=', 1);
      recurrence_value := split_part(recurrence_part, '=', 2);
      IF recurrence_key = ANY(seen_keys) THEN
        RAISE EXCEPTION 'Automated schedule recurrence contains duplicate options' USING ERRCODE = '23514';
      END IF;
      seen_keys := array_append(seen_keys, recurrence_key);

      IF recurrence_key = 'FREQ' THEN
        IF recurrence_value <> upper(NEW.frequency) OR recurrence_value NOT IN ('DAILY','WEEKLY','MONTHLY') THEN
          RAISE EXCEPTION 'Automated schedule frequency does not match RRULE' USING ERRCODE = '23514';
        END IF;
      ELSIF recurrence_key = 'INTERVAL' THEN
        IF recurrence_value !~ '^[1-9][0-9]{0,2}$' THEN
          RAISE EXCEPTION 'Automated schedule INTERVAL is invalid' USING ERRCODE = '23514';
        END IF;
        IF recurrence_value::integer > 365 THEN
          RAISE EXCEPTION 'Automated schedule INTERVAL is invalid' USING ERRCODE = '23514';
        END IF;
      ELSIF recurrence_key = 'BYDAY' THEN
        IF NEW.frequency <> 'Weekly' OR recurrence_value !~ '^(MO|TU|WE|TH|FR|SA|SU)$' THEN
          RAISE EXCEPTION 'Automated weekly BYDAY is invalid' USING ERRCODE = '23514';
        END IF;
      ELSIF recurrence_key = 'BYMONTHDAY' THEN
        IF NEW.frequency <> 'Monthly' OR recurrence_value !~ '^([1-9]|[12][0-9]|3[01])$' THEN
          RAISE EXCEPTION 'Automated monthly BYMONTHDAY is invalid' USING ERRCODE = '23514';
        END IF;
      ELSE
        RAISE EXCEPTION 'Automated schedule recurrence option is unsupported' USING ERRCODE = '23514';
      END IF;
    END LOOP;

    IF NOT ('FREQ' = ANY(seen_keys)) THEN
      RAISE EXCEPTION 'Automated schedule recurrence requires FREQ' USING ERRCODE = '23514';
    END IF;
    SELECT status INTO profile_status FROM zap_scan_profile WHERE id = NEW.zap_profile_id;
    IF profile_status IS DISTINCT FROM 'Active'::zap_profile_status THEN
      RAISE EXCEPTION 'Automated schedule requires an active ZAP profile' USING ERRCODE = '23514';
    END IF;
  END IF;
  RETURN NEW;
END $$;

CREATE TRIGGER check_automated_schedule
BEFORE INSERT OR UPDATE OF automation_enabled, zap_profile_id, status, frequency, recurrence_rule
ON scan_schedule FOR EACH ROW EXECUTE FUNCTION guard_automated_schedule();

CREATE OR REPLACE FUNCTION guard_zap_execution_identity()
RETURNS trigger LANGUAGE plpgsql SET search_path = htqlhdk, pg_temp AS $$
BEGIN
  IF ROW(NEW.code, NEW.scan_id, NEW.profile_id, NEW.service_user_id,
         NEW.requested_at, NEW.image_reference, NEW.configuration_snapshot)
     IS DISTINCT FROM
     ROW(OLD.code, OLD.scan_id, OLD.profile_id, OLD.service_user_id,
         OLD.requested_at, OLD.image_reference, OLD.configuration_snapshot) THEN
    RAISE EXCEPTION 'ZAP execution identity and snapshot are immutable' USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END $$;

CREATE TRIGGER protect_zap_execution_identity
BEFORE UPDATE ON zap_execution FOR EACH ROW EXECUTE FUNCTION guard_zap_execution_identity();

CREATE OR REPLACE FUNCTION deny_zap_artifact_mutation()
RETURNS trigger LANGUAGE plpgsql SET search_path = htqlhdk, pg_temp AS $$
BEGIN
  RAISE EXCEPTION 'ZAP artifact metadata is immutable' USING ERRCODE = '23514';
END $$;

CREATE TRIGGER protect_zap_artifact
BEFORE UPDATE OR DELETE ON zap_artifact FOR EACH ROW EXECUTE FUNCTION deny_zap_artifact_mutation();

CREATE VIEW v_zap_execution_summary AS
SELECT e.id, e.code, e.scan_id, s.asset_id, e.profile_id, p.code AS profile_code,
       p.version_no AS profile_version, e.status, e.attempt_count, e.requested_at,
       e.started_at, e.heartbeat_at, e.finished_at, e.exit_code, e.failure_code,
       e.import_batch_id
FROM zap_execution e
JOIN scan_occurrence s ON s.id = e.scan_id
JOIN zap_scan_profile p ON p.id = e.profile_id;

COMMIT;
