BEGIN;
SET search_path = htqlhdk, public;

CREATE TYPE zap_profile_status AS ENUM ('Draft', 'Active', 'Retired');
CREATE TYPE zap_spider_kind AS ENUM ('Traditional', 'Client');
CREATE TYPE zap_auth_kind AS ENUM ('None', 'Header');
CREATE TYPE zap_execution_status AS ENUM (
  'Queued',
  'Preparing Plan',
  'Starting Runner',
  'Running',
  'Collecting Report',
  'Report Received',
  'Failed',
  'Timed Out',
  'Cancelled'
);

CREATE TABLE zap_scan_profile (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code varchar(40) NOT NULL,
  name text NOT NULL,
  version_no integer NOT NULL CHECK (version_no > 0),
  status zap_profile_status NOT NULL DEFAULT 'Draft',
  spider_kind zap_spider_kind NOT NULL DEFAULT 'Traditional',
  active_scan_enabled boolean NOT NULL DEFAULT false,
  auth_kind zap_auth_kind NOT NULL DEFAULT 'None',
  auth_header_name text,
  auth_secret_ref text,
  spider_max_minutes integer NOT NULL DEFAULT 10 CHECK (spider_max_minutes BETWEEN 1 AND 1440),
  passive_wait_max_minutes integer NOT NULL DEFAULT 10 CHECK (passive_wait_max_minutes BETWEEN 1 AND 1440),
  active_scan_max_minutes integer NOT NULL DEFAULT 30 CHECK (active_scan_max_minutes BETWEEN 1 AND 1440),
  max_rule_minutes integer NOT NULL DEFAULT 5 CHECK (max_rule_minutes BETWEEN 1 AND 1440),
  request_delay_ms integer NOT NULL DEFAULT 100 CHECK (request_delay_ms BETWEEN 0 AND 60000),
  thread_per_host integer NOT NULL DEFAULT 2 CHECK (thread_per_host BETWEEN 1 AND 32),
  service_user_id bigint NOT NULL,
  created_by bigint NOT NULL,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  approved_by bigint,
  approved_at timestamptz,
  retired_at timestamptz,
  UNIQUE (code, version_no),
  UNIQUE (id, service_user_id),
  CHECK ((approved_by IS NULL) = (approved_at IS NULL)),
  CHECK (status <> 'Active' OR approved_by IS NOT NULL),
  CHECK ((status = 'Retired') = (retired_at IS NOT NULL)),
  CHECK (
    (auth_kind = 'None' AND auth_header_name IS NULL AND auth_secret_ref IS NULL)
    OR
    (auth_kind = 'Header'
      AND NULLIF(btrim(auth_header_name), '') IS NOT NULL
      AND auth_header_name ~ '^[A-Za-z0-9-]+$'
      AND auth_secret_ref ~ '^env:HTQLHDK_ZAP_[A-Z0-9_]+$')
  )
);

COMMENT ON TABLE zap_scan_profile IS 'Cấu hình Automation Framework có phiên bản; không lưu giá trị credential/token.';
COMMENT ON COLUMN zap_scan_profile.auth_secret_ref IS 'Chỉ tham chiếu env:HTQLHDK_ZAP_*, không chứa giá trị bí mật.';
COMMENT ON COLUMN zap_scan_profile.service_user_id IS 'Tài khoản dịch vụ không đăng nhập dùng cho performed_by/imported_by.';

ALTER TABLE scan_schedule
  ADD COLUMN automation_enabled boolean NOT NULL DEFAULT false,
  ADD COLUMN zap_profile_id bigint,
  ADD CONSTRAINT ck_scan_schedule_automation_profile
    CHECK (NOT automation_enabled OR zap_profile_id IS NOT NULL),
  ADD CONSTRAINT fk_scan_schedule_zap_profile
    FOREIGN KEY (zap_profile_id) REFERENCES zap_scan_profile(id)
    ON DELETE RESTRICT ON UPDATE RESTRICT;

COMMENT ON COLUMN scan_schedule.automation_enabled IS 'True khi kỳ đến hạn được Worker tự động chạy bằng ZAP Automation Framework.';
COMMENT ON COLUMN scan_schedule.zap_profile_id IS 'Phiên bản cấu hình ZAP được phê duyệt; NULL giữ luồng quét bên ngoài cũ.';

CREATE TABLE zap_execution (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code varchar(40) NOT NULL UNIQUE,
  scan_id bigint NOT NULL UNIQUE,
  profile_id bigint NOT NULL,
  service_user_id bigint NOT NULL,
  status zap_execution_status NOT NULL DEFAULT 'Queued',
  attempt_count integer NOT NULL DEFAULT 0 CHECK (attempt_count BETWEEN 0 AND 10),
  max_attempts integer NOT NULL DEFAULT 1 CHECK (max_attempts BETWEEN 1 AND 10),
  requested_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  started_at timestamptz,
  heartbeat_at timestamptz,
  finished_at timestamptz,
  lease_owner varchar(120),
  lease_expires_at timestamptz,
  cancel_requested_at timestamptz,
  runner_name varchar(120),
  exit_code integer,
  failure_code varchar(80),
  failure_message_masked text,
  zap_version text,
  image_reference text NOT NULL,
  configuration_snapshot jsonb NOT NULL,
  import_batch_id bigint UNIQUE,
  UNIQUE (id, scan_id),
  CHECK ((lease_owner IS NULL) = (lease_expires_at IS NULL)),
  CHECK (heartbeat_at IS NULL OR started_at IS NOT NULL),
  CHECK (finished_at IS NULL OR started_at IS NULL OR finished_at >= started_at),
  CHECK (status NOT IN ('Report Received','Failed','Timed Out','Cancelled') OR finished_at IS NOT NULL),
  CHECK (status <> 'Report Received' OR import_batch_id IS NOT NULL),
  CHECK (status NOT IN ('Failed','Timed Out') OR NULLIF(btrim(failure_code), '') IS NOT NULL),
  CHECK (image_reference ~ '@sha256:[0-9a-f]{64}$')
);

COMMENT ON TABLE zap_execution IS 'Trạng thái kỹ thuật của một container ZAP tách khỏi trạng thái nghiệp vụ ScanOccurrence.';
COMMENT ON COLUMN zap_execution.configuration_snapshot IS 'Bản chụp cấu hình đã che bí mật và bất biến sau khi tạo.';
COMMENT ON COLUMN zap_execution.lease_owner IS 'Worker đang giữ lease; dùng để phục hồi khi tiến trình chết.';

CREATE TABLE zap_artifact (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  execution_id bigint NOT NULL,
  artifact_kind text NOT NULL,
  object_key text NOT NULL UNIQUE,
  sha256 varchar(64) NOT NULL,
  media_type text NOT NULL,
  size_bytes bigint NOT NULL CHECK (size_bytes > 0),
  key_ref text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (execution_id, artifact_kind),
  CHECK (artifact_kind IN ('Traditional JSON','Traditional HTML')),
  CHECK (sha256 ~ '^[0-9a-f]{64}$'),
  CHECK (media_type IN ('application/json','text/html'))
);

COMMENT ON TABLE zap_artifact IS 'Metadata báo cáo do ZAP Runner sinh ra; nội dung nằm trong kho tệp riêng.';

ALTER TABLE zap_scan_profile
  ADD CONSTRAINT fk_zap_scan_profile_service_user
    FOREIGN KEY (service_user_id) REFERENCES app_user(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  ADD CONSTRAINT fk_zap_scan_profile_created_by
    FOREIGN KEY (created_by) REFERENCES app_user(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  ADD CONSTRAINT fk_zap_scan_profile_approved_by
    FOREIGN KEY (approved_by) REFERENCES app_user(id) ON DELETE RESTRICT ON UPDATE RESTRICT;

ALTER TABLE zap_execution
  ADD CONSTRAINT fk_zap_execution_scan
    FOREIGN KEY (scan_id) REFERENCES scan_occurrence(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  ADD CONSTRAINT fk_zap_execution_profile_service
