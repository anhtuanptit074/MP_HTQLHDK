BEGIN;
CREATE SCHEMA htqlhdk;
REVOKE ALL ON SCHEMA htqlhdk FROM PUBLIC;
SET search_path=htqlhdk,public;

CREATE TABLE app_user (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username varchar(120) NOT NULL UNIQUE CHECK(username=lower(username)), display_name text NOT NULL,
 account_kind text NOT NULL DEFAULT 'Human' CHECK(account_kind IN ('Human','Service')),
 password_hash text, is_active boolean NOT NULL DEFAULT true, created_at timestamptz NOT NULL DEFAULT now(),
 CHECK(account_kind<>'Service' OR password_hash IS NULL)
);
CREATE TABLE asset (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code varchar(40) NOT NULL UNIQUE, name text NOT NULL,
 base_url text NOT NULL CHECK(base_url ~ '^https?://'), environment text NOT NULL,
 owner_id bigint NOT NULL REFERENCES app_user, security_officer_id bigint NOT NULL REFERENCES app_user,
 criticality text NOT NULL, data_classification text NOT NULL DEFAULT 'Internal', internet_exposed boolean NOT NULL DEFAULT false,
 status text NOT NULL DEFAULT 'Draft' CHECK(status IN ('Draft','Pending Approval','Active','Suspended','Retired')),
 created_by bigint NOT NULL REFERENCES app_user, created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE user_role (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id bigint NOT NULL REFERENCES app_user,
 role_code text NOT NULL CHECK(role_code IN ('ADMIN','SECURITY','SCAN_OPERATOR','REMEDIATOR','AUDITOR')),
 asset_id bigint REFERENCES asset, granted_by bigint NOT NULL REFERENCES app_user, granted_at timestamptz NOT NULL DEFAULT now(),
 revoked_by bigint REFERENCES app_user, revoked_at timestamptz,
 CHECK(role_code<>'ADMIN' OR asset_id IS NULL), CHECK((revoked_by IS NULL)=(revoked_at IS NULL))
);
CREATE UNIQUE INDEX uq_active_role ON user_role(user_id,role_code,asset_id) NULLS NOT DISTINCT WHERE revoked_at IS NULL;
CREATE TABLE asset_scope_revision (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, asset_id bigint NOT NULL REFERENCES asset, version_no int NOT NULL CHECK(version_no>0),
 status text NOT NULL DEFAULT 'Draft' CHECK(status IN ('Draft','Pending Approval','Approved','Rejected')),
 change_reason text NOT NULL, created_by bigint NOT NULL REFERENCES app_user, created_at timestamptz NOT NULL DEFAULT now(),
 confirmed_by bigint REFERENCES app_user, confirmed_at timestamptz, decided_by bigint REFERENCES app_user, decided_at timestamptz,
 decision_reason text, effective_from timestamptz, effective_until timestamptz,
 UNIQUE(asset_id,version_no), CHECK((confirmed_by IS NULL)=(confirmed_at IS NULL)), CHECK((decided_by IS NULL)=(decided_at IS NULL)),
 CHECK(status NOT IN ('Pending Approval','Approved') OR confirmed_by IS NOT NULL),
 CHECK(status NOT IN ('Approved','Rejected') OR (decided_by IS NOT NULL AND length(btrim(decision_reason))>0)),
 CHECK(status<>'Approved' OR effective_from IS NOT NULL), CHECK(effective_until IS NULL OR effective_until>effective_from)
);
CREATE TABLE asset_scope_rule (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, scope_id bigint NOT NULL REFERENCES asset_scope_revision,
 effect text NOT NULL CHECK(effect IN ('Include','Exclude')), target_type text NOT NULL CHECK(target_type IN ('Domain','Subdomain','URL')),
 target_value text NOT NULL, match_mode text NOT NULL CHECK(match_mode IN ('Exact','Prefix')),
 CHECK(match_mode<>'Prefix' OR target_type='URL'), UNIQUE(scope_id,effect,target_type,target_value,match_mode)
);
CREATE TABLE asset_scan_window (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, scope_id bigint NOT NULL REFERENCES asset_scope_revision,
 weekday_iso smallint NOT NULL CHECK(weekday_iso BETWEEN 1 AND 7), start_time time NOT NULL,end_time time NOT NULL,
 ends_next_day boolean NOT NULL DEFAULT false, timezone text NOT NULL,
 CHECK((NOT ends_next_day AND end_time>start_time) OR (ends_next_day AND end_time<=start_time)),
 UNIQUE(scope_id,weekday_iso,start_time,end_time,ends_next_day,timezone)
);
CREATE TABLE zap_scan_profile (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code varchar(40) NOT NULL, name text NOT NULL, version_no int NOT NULL CHECK(version_no>0),
 status text NOT NULL DEFAULT 'Draft' CHECK(status IN ('Draft','Pending Approval','Active','Retired')),
 spider_kind text NOT NULL DEFAULT 'Traditional' CHECK(spider_kind IN ('Traditional','Client')),
 passive_scan_enabled boolean NOT NULL DEFAULT true, active_scan_enabled boolean NOT NULL DEFAULT false,
 max_duration_minutes int NOT NULL DEFAULT 30 CHECK(max_duration_minutes BETWEEN 1 AND 1440),
 request_delay_ms int NOT NULL DEFAULT 250 CHECK(request_delay_ms BETWEEN 0 AND 60000), thread_per_host int NOT NULL DEFAULT 2 CHECK(thread_per_host BETWEEN 1 AND 16),
 auth_kind text NOT NULL DEFAULT 'None' CHECK(auth_kind IN ('None','Header')),auth_header_name text,auth_secret_ref text,
 report_format text NOT NULL DEFAULT 'JSON' CHECK(report_format IN ('JSON','XML')),
 service_user_id bigint NOT NULL REFERENCES app_user,created_by bigint NOT NULL REFERENCES app_user,created_at timestamptz NOT NULL DEFAULT now(),
 approved_by bigint REFERENCES app_user,approved_at timestamptz,retired_at timestamptz,
 UNIQUE(code,version_no), CHECK(status NOT IN ('Active','Retired') OR approved_by IS NOT NULL),
 CHECK((status='Retired')=(retired_at IS NOT NULL)),
 CHECK((auth_kind='None' AND auth_header_name IS NULL AND auth_secret_ref IS NULL) OR
       (auth_kind='Header' AND auth_header_name ~ '^[A-Za-z0-9-]+$' AND auth_secret_ref ~ '^env:HTQLHDK_ZAP_[A-Z0-9_]+$'))
);
CREATE TABLE finding (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, asset_id bigint NOT NULL REFERENCES asset,code varchar(40) NOT NULL UNIQUE,
 fingerprint varchar(64) NOT NULL CHECK(fingerprint ~ '^[a-f0-9]{64}$'),identity_version smallint NOT NULL DEFAULT 1,
 identity_key_ref text NOT NULL,identity_ciphertext bytea NOT NULL,source_alert_ref text NOT NULL,
 affected_url_masked text NOT NULL,parameter_masked text,input_vector_masked text,http_method text NOT NULL DEFAULT '',title_masked text NOT NULL,
 final_severity text CHECK(final_severity IN ('Informational','Low','Medium','High','Critical')),severity_reason text,
 assessed_by bigint REFERENCES app_user,assessed_at timestamptz,
 status text NOT NULL DEFAULT 'New' CHECK(status IN ('New','Triaged','Assigned','In Progress','Pending Verification','Closed','Reopened','False Positive','Cancelled')),
 decision_reason text,decision_by bigint REFERENCES app_user,decision_at timestamptz,created_at timestamptz NOT NULL DEFAULT now(),row_version bigint NOT NULL DEFAULT 1,
 UNIQUE(asset_id,fingerprint), CHECK((assessed_by IS NULL)=(assessed_at IS NULL)),CHECK(final_severity IS NULL OR assessed_by IS NOT NULL)
);
CREATE TABLE remediation_ticket (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,finding_id bigint NOT NULL UNIQUE REFERENCES finding,code varchar(40) NOT NULL UNIQUE,
 assignee_id bigint NOT NULL REFERENCES app_user,assigned_by bigint NOT NULL REFERENCES app_user,assigned_at timestamptz NOT NULL DEFAULT now(),due_at timestamptz NOT NULL,
 progress_percent smallint NOT NULL DEFAULT 0 CHECK(progress_percent BETWEEN 0 AND 100),root_cause_masked text,remediation_action_masked text,
 evidence_summary_masked text,evidence_object_key text,evidence_sha256 varchar(64),evidence_key_ref text,remediated_at timestamptz,
 created_by bigint NOT NULL REFERENCES app_user,created_at timestamptz NOT NULL DEFAULT now(),updated_by bigint NOT NULL REFERENCES app_user,updated_at timestamptz NOT NULL DEFAULT now(),
 CHECK((evidence_object_key IS NULL AND evidence_sha256 IS NULL AND evidence_key_ref IS NULL) OR
       (evidence_object_key IS NOT NULL AND evidence_sha256 ~ '^[a-f0-9]{64}$' AND evidence_key_ref IS NOT NULL))
);
CREATE TABLE scan_plan (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,code varchar(40) NOT NULL,version_no int NOT NULL DEFAULT 1 CHECK(version_no>0),name text NOT NULL,
 plan_kind text NOT NULL CHECK(plan_kind IN ('Periodic','Verification')),scope_id bigint NOT NULL REFERENCES asset_scope_revision,
 zap_profile_id bigint NOT NULL REFERENCES zap_scan_profile,operator_id bigint NOT NULL REFERENCES app_user,
 status text NOT NULL DEFAULT 'Draft' CHECK(status IN ('Draft','Active','Paused','Expired','Cancelled')),
 recurrence_rule text,timezone text,effective_from timestamptz,effective_until timestamptz,
 remediation_ticket_id bigint REFERENCES remediation_ticket,requested_for timestamptz,
 created_by bigint NOT NULL REFERENCES app_user,created_at timestamptz NOT NULL DEFAULT now(),approved_by bigint REFERENCES app_user,approved_at timestamptz,
 UNIQUE(code,version_no), CHECK((plan_kind='Periodic' AND recurrence_rule IS NOT NULL AND timezone IS NOT NULL AND effective_from IS NOT NULL AND remediation_ticket_id IS NULL AND requested_for IS NULL)
 OR (plan_kind='Verification' AND recurrence_rule IS NULL AND timezone IS NULL AND effective_from IS NULL AND effective_until IS NULL AND remediation_ticket_id IS NOT NULL AND requested_for IS NOT NULL)),
 CHECK(effective_until IS NULL OR effective_until>effective_from),CHECK(status<>'Active' OR approved_by IS NOT NULL)
);
CREATE TABLE scan_run (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,plan_id bigint NOT NULL REFERENCES scan_plan,code varchar(40) NOT NULL UNIQUE,scheduled_for timestamptz NOT NULL,
 scan_status text NOT NULL DEFAULT 'Planned' CHECK(scan_status IN ('Planned','Queued','Running','Completed','Failed','Timed Out','Cancelled')),
 requested_at timestamptz NOT NULL DEFAULT now(),started_at timestamptz,heartbeat_at timestamptz,finished_at timestamptz,
 external_plan_id text,external_session_id text,cancel_requested_at timestamptz,runner_name text,image_reference text,zap_version text,exit_code int,
 failure_code text,failure_message_masked text,
 report_status text NOT NULL DEFAULT 'Not Received' CHECK(report_status IN ('Not Received','Validating','Processed','Rejected','Failed')),
 report_object_key text,report_sha256 varchar(64),report_size_bytes bigint,report_format text CHECK(report_format IN ('JSON','XML')),
 report_key_ref text,report_received_at timestamptz,
 coverage_confirmed boolean,fingerprint_present boolean,verification_outcome text CHECK(verification_outcome IN ('Closed','Reopened')),
 verification_reason text,evaluated_by bigint REFERENCES app_user,evaluated_at timestamptz,
 UNIQUE(plan_id,scheduled_for), CHECK(finished_at IS NULL OR started_at IS NULL OR finished_at>=started_at),
 CHECK(scan_status NOT IN ('Completed','Failed','Timed Out','Cancelled') OR finished_at IS NOT NULL),
 CHECK(report_status<>'Processed' OR (scan_status='Completed' AND report_object_key IS NOT NULL AND report_sha256 ~ '^[a-f0-9]{64}$')),
 CHECK(verification_outcome IS NULL OR (evaluated_by IS NOT NULL AND evaluated_at IS NOT NULL AND verification_reason IS NOT NULL)),
 CHECK(verification_outcome<>'Closed' OR (coverage_confirmed AND fingerprint_present IS FALSE AND report_status='Processed'))
);
CREATE TABLE finding_occurrence (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,finding_id bigint NOT NULL REFERENCES finding,scan_run_id bigint NOT NULL REFERENCES scan_run,
 record_locator text NOT NULL,source_severity text NOT NULL CHECK(source_severity IN ('Informational','Low','Medium','High')),
 source_confidence smallint NOT NULL CHECK(source_confidence BETWEEN 0 AND 4),source_attack_masked text,source_evidence_masked text,
 description_masked text,technical_details_masked text,remediation_guidance_masked text,cwe_id int,wasc_id int,created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(finding_id,scan_run_id),UNIQUE(scan_run_id,record_locator)
);
CREATE TABLE audit_log (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,actor_id bigint REFERENCES app_user,actor_kind text NOT NULL CHECK(actor_kind IN ('Human','Service','Anonymous')),
 occurred_at timestamptz NOT NULL DEFAULT now(),category text NOT NULL CHECK(category IN ('Permission','Business','Security')),
 action text NOT NULL,object_type text NOT NULL,object_id text NOT NULL,outcome text NOT NULL CHECK(outcome IN ('Success','Denied','Failure')),
 before_masked jsonb,after_masked jsonb,reason_masked text,correlation_id uuid NOT NULL
);
CREATE INDEX ix_run_queue ON scan_run(scan_status,scheduled_for);
CREATE INDEX ix_finding_worklist ON finding(asset_id,status);
CREATE INDEX ix_ticket_assignee ON remediation_ticket(assignee_id,due_at);
CREATE INDEX ix_role_actor ON user_role(user_id,asset_id) WHERE revoked_at IS NULL;
CREATE INDEX ix_audit_object ON audit_log(object_type,object_id,occurred_at);

CREATE FUNCTION protect_history() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'Immutable history' USING ERRCODE='23514'; END $$;
CREATE TRIGGER audit_immutable BEFORE UPDATE OR DELETE ON audit_log FOR EACH ROW EXECUTE FUNCTION protect_history();
CREATE TRIGGER occurrence_immutable BEFORE UPDATE OR DELETE ON finding_occurrence FOR EACH ROW EXECUTE FUNCTION protect_history();
CREATE FUNCTION guard_scope() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_OP='DELETE' OR (TG_OP='UPDATE' AND OLD.status IN ('Approved','Rejected')) THEN RAISE EXCEPTION 'Scope is immutable' USING ERRCODE='23514'; END IF;
 IF NEW.status='Approved' THEN
  PERFORM pg_advisory_xact_lock(NEW.asset_id);
  IF EXISTS(SELECT 1 FROM htqlhdk.asset_scope_revision s WHERE s.asset_id=NEW.asset_id AND s.id<>NEW.id AND s.status='Approved'
    AND tstzrange(s.effective_from,s.effective_until,'[)') && tstzrange(NEW.effective_from,NEW.effective_until,'[)')) THEN
   RAISE EXCEPTION 'Approved scope intervals overlap' USING ERRCODE='23514';
  END IF;
 END IF; RETURN NEW;
END $$;
CREATE TRIGGER scope_guard BEFORE UPDATE OR DELETE ON asset_scope_revision FOR EACH ROW EXECUTE FUNCTION guard_scope();
CREATE FUNCTION guard_scope_child() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE scope_state text; scope_key bigint;
BEGIN
 scope_key:=CASE WHEN TG_OP='DELETE' THEN OLD.scope_id ELSE NEW.scope_id END;
 SELECT status INTO scope_state FROM htqlhdk.asset_scope_revision WHERE id=scope_key FOR SHARE;
 IF scope_state<>'Draft' THEN RAISE EXCEPTION 'Scope children are immutable' USING ERRCODE='23514'; END IF;
 IF TG_OP='UPDATE' AND NEW.scope_id<>OLD.scope_id THEN RAISE EXCEPTION 'Cannot move scope child' USING ERRCODE='23514'; END IF;
 RETURN CASE WHEN TG_OP='DELETE' THEN OLD ELSE NEW END;
END $$;
CREATE TRIGGER rule_guard BEFORE INSERT OR UPDATE OR DELETE ON asset_scope_rule FOR EACH ROW EXECUTE FUNCTION guard_scope_child();
CREATE TRIGGER window_guard BEFORE INSERT OR UPDATE OR DELETE ON asset_scan_window FOR EACH ROW EXECUTE FUNCTION guard_scope_child();
CREATE FUNCTION guard_plan() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_OP='UPDATE' AND EXISTS(SELECT 1 FROM htqlhdk.scan_run WHERE plan_id=OLD.id) AND
 (to_jsonb(NEW)-ARRAY['status']) IS DISTINCT FROM (to_jsonb(OLD)-ARRAY['status']) THEN RAISE EXCEPTION 'Used plan needs a new version' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER plan_guard BEFORE UPDATE ON scan_plan FOR EACH ROW EXECUTE FUNCTION guard_plan();
CREATE FUNCTION guard_profile() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF OLD.status='Retired' OR (OLD.status='Active' AND NOT (NEW.status='Retired' AND
 (to_jsonb(NEW)-ARRAY['status','retired_at'])=(to_jsonb(OLD)-ARRAY['status','retired_at']))) THEN RAISE EXCEPTION 'Profile is immutable' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER profile_guard BEFORE UPDATE ON zap_scan_profile FOR EACH ROW EXECUTE FUNCTION guard_profile();
CREATE FUNCTION guard_run() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE kind text;
BEGIN
 SELECT plan_kind INTO kind FROM htqlhdk.scan_plan WHERE id=NEW.plan_id FOR UPDATE;
 IF TG_OP='INSERT' AND kind='Verification' AND EXISTS(SELECT 1 FROM htqlhdk.scan_run WHERE plan_id=NEW.plan_id) THEN RAISE EXCEPTION 'Verification plan has one run' USING ERRCODE='23514'; END IF;
 IF NEW.verification_outcome IS NOT NULL AND kind<>'Verification' THEN RAISE EXCEPTION 'Not a verification run' USING ERRCODE='23514'; END IF;
 IF TG_OP='UPDATE' THEN
  IF NEW.plan_id<>OLD.plan_id OR NEW.scheduled_for<>OLD.scheduled_for OR NEW.code<>OLD.code THEN RAISE EXCEPTION 'Run identity immutable' USING ERRCODE='23514'; END IF;
  IF OLD.report_object_key IS NOT NULL AND ROW(NEW.report_object_key,NEW.report_sha256,NEW.report_size_bytes,NEW.report_format,NEW.report_key_ref)
   IS DISTINCT FROM ROW(OLD.report_object_key,OLD.report_sha256,OLD.report_size_bytes,OLD.report_format,OLD.report_key_ref) THEN RAISE EXCEPTION 'Report is immutable' USING ERRCODE='23514'; END IF;
  IF OLD.verification_outcome IS NOT NULL THEN RAISE EXCEPTION 'Verification is immutable' USING ERRCODE='23514'; END IF;
 END IF; RETURN NEW;
END $$;
CREATE TRIGGER run_guard BEFORE INSERT OR UPDATE ON scan_run FOR EACH ROW EXECUTE FUNCTION guard_run();
CREATE FUNCTION guard_finding() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE allowed boolean;
BEGIN
 IF NEW.asset_id<>OLD.asset_id OR NEW.fingerprint<>OLD.fingerprint OR NEW.identity_ciphertext<>OLD.identity_ciphertext THEN RAISE EXCEPTION 'Finding identity immutable' USING ERRCODE='23514'; END IF;
 IF NEW.status<>OLD.status THEN
 allowed:=CASE OLD.status
 WHEN 'New' THEN NEW.status IN ('Triaged','False Positive','Cancelled') WHEN 'Triaged' THEN NEW.status IN ('Assigned','False Positive','Cancelled')
 WHEN 'Assigned' THEN NEW.status='In Progress' WHEN 'In Progress' THEN NEW.status='Pending Verification'
 WHEN 'Pending Verification' THEN NEW.status IN ('Closed','Reopened') WHEN 'Closed' THEN NEW.status='Reopened'
 WHEN 'Reopened' THEN NEW.status='Assigned' ELSE false END;
 IF NOT allowed THEN RAISE EXCEPTION 'Invalid finding transition' USING ERRCODE='23514'; END IF;
 END IF;
 IF NEW.status='Triaged' AND NEW.final_severity IS NULL THEN RAISE EXCEPTION 'Severity required' USING ERRCODE='23514'; END IF;
 NEW.row_version:=OLD.row_version+1; RETURN NEW;
END $$;
CREATE TRIGGER finding_guard BEFORE UPDATE ON finding FOR EACH ROW EXECUTE FUNCTION guard_finding();
COMMIT;
